#!/usr/bin/env python3
"""Print llama-swap's config.yaml for the i9 or the Mac, from llm/models.json.

    llama_swap_config.py [--machine i9|mac]     (machine default: detected)

i9:  one entry per GGUF on disk. Each `cmd` runs llm/i9/start.sh with IK_LLAMA_PRINT_CMD=1 and evals
     the printed command, so llama-swap starts exactly the server start.sh would (one flag builder).
mac: Ollama is a peer (it loads models itself); llama-swap forces thinking off in every request, for
     both API formats. Each model also gets a selector under its readable id, which agents use.
Both: the model's `id` from models.json is its one name (model page, stats, agents); `desc` becomes the
description shown under it.

The ProBook's equivalent is llm/probook/llama-swap-setup.ps1 (Windows quoting, PowerShell flag builder).
json.dumps() output is used for every string: it is a valid YAML double-quoted scalar.
"""
import argparse
import json
import os
import sys
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from models import LLAMA_ROOT, detect_machine, load_modes  # noqa: E402

LLM_DIR = Path(__file__).resolve().parent.parent
q = json.dumps


def header():
    return ['# Generated by llm/llama-swap-setup.sh -- re-run it instead of editing.',
            'logLevel: info',
            # bounded in-memory stats for llama-swap's own UI
            'metricsMaxInMemory: 1000',
            # lets a client tell a cold model load from a stalled request
            'sendLoadingState: true']


def i9_config():
    models_dir = Path(os.environ.get('MODELS_DIR') or LLAMA_ROOT / 'models')
    start = LLM_DIR / 'i9' / 'start.sh'
    out = header() + [f"healthCheckTimeout: {int(os.environ.get('IK_LLAMA_SWAP_HEALTH_TIMEOUT', '600'))}", 'models:']
    n = 0
    for m in load_modes('i9'):
        if not (models_dir / m['file']).is_file():
            print(f"  - {m['file']}: skipped (not in {models_dir})", file=sys.stderr)
            continue
        mid = m.get('id') or m['file'][:-len('.gguf')]   # the one readable name; start.sh takes the file stem
        mode = m['file'][:-len('.gguf')]
        out.append(f'  {q(mid)}:')
        if m.get('desc'):
            out.append(f"    description: {q(m['desc'])}")
        inner = f'eval "$(IK_LLAMA_PRINT_CMD=1 IK_LLAMA_PORT=${{PORT}} {q(str(start))} i9 {q(mode)})"'
        out.append(f'    cmd: bash -c {q(inner)}')
        out.append('    proxy: "http://127.0.0.1:${PORT}"')
        out.append('    ttl: 0')
        n += 1
    return out, n


def mac_config():
    port = os.environ.get('OLLAMA_HOST_PORT', '11434')
    with urllib.request.urlopen(f'http://127.0.0.1:{port}/api/tags', timeout=5) as r:
        have = {t['name'].removesuffix(':latest') for t in json.load(r)['models']}
    entries = []
    for m in load_modes('mac'):
        if m['ollama'] in have:
            entries.append(m)
        else:
            print(f"  - {m['ollama']}: skipped (not in Ollama; ollama pull {m.get('source', '')})", file=sys.stderr)
    out = header() + ['peers:', '  ollama:', f'    proxy: http://127.0.0.1:{port}',
                      '    timeouts:',
                      '      responseHeader: 600   # a cold load plus a long prompt can exceed the 60 s default',
                      '    filters:', '      setParams:',
                      '        reasoning_effort: none   # OpenAI format (OpenCode, Pi)',
                      "        thinking:                # Anthropic format (Claude Code); each ignores the other's field",
                      '          type: disabled',
                      '    models:']
    out += [f"      - {q(m['ollama'])}" for m in entries]
    if entries:
        out.append('selectors:')
        for m in entries:
            out += [f"  {q(m['id'])}:", '    strategy: pin', f"    targets: [{q('ollama/' + m['ollama'])}]"]
            if m.get('desc'):
                out.append(f"    description: {q(m['desc'])}")
    return out, len(entries)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--machine', choices=('i9', 'mac'))
    args = ap.parse_args()
    machine = args.machine or detect_machine()
    if machine not in ('i9', 'mac'):
        sys.exit('llama_swap_config.py: not an i9 or a Mac (ProBook: llm\\probook\\llama-swap-setup.ps1); '
                 'pass --machine i9|mac or set LLM_MACHINE.')
    try:
        lines, n = i9_config() if machine == 'i9' else mac_config()
    except OSError as e:
        sys.exit(f'llama_swap_config.py: Ollama is not answering ({e}); start it first.')
    if n == 0:
        sys.exit(f'llama_swap_config.py: no {machine} model is available here; nothing to serve.')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
