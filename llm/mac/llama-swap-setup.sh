#!/usr/bin/env bash
# The Mac's daily start, same chain as the ProBook and the i9:
#   agents -> local-proxy.py (9081, keep-alives) -> llama-swap (9082, web UI + stats) -> Ollama (11434)
# Starts Ollama if it is not up, writes the llama-swap config, starts llama-swap and local-proxy.
# Ollama keeps loading and swapping models itself; llama-swap forwards to it as a "peer" and turns
# thinking off in every request (both API formats), so it is off here as on the other machines.
# Usage: ./llama-swap-setup.sh      Stop everything: ./stop.sh      Web UI: http://127.0.0.1:9082/ui
# Install once: ../../tools/llama-swap-install.sh
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SHARED_DIR="$(cd "$SCRIPT_DIR/../shared" && pwd)"
OLLAMA_PORT="${OLLAMA_HOST_PORT:-11434}"
SWAP_LISTEN="${LLAMA_SWAP_PORT:-9082}"
AGENT_PORT="${LOCAL_PROXY_PORT:-9081}"
CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/llama-swap"
CONFIG_FILE="$CONFIG_DIR/config.yaml"
LOG_FILE="${TMPDIR:-/tmp}/llama-swap.log"

LLAMA_SWAP_BIN="${LLAMA_SWAP_BIN:-$(command -v llama-swap || echo '')}"
# Non-interactive shells (ssh, launchd) do not get Homebrew's PATH.
[ -n "$LLAMA_SWAP_BIN" ] || { [ -x /opt/homebrew/bin/llama-swap ] && LLAMA_SWAP_BIN=/opt/homebrew/bin/llama-swap; }
[ -n "$LLAMA_SWAP_BIN" ] || { echo "llama-swap not found. Install: ../../tools/llama-swap-install.sh" >&2; exit 1; }

if ! curl -sf "http://127.0.0.1:$OLLAMA_PORT/api/version" >/dev/null 2>&1; then
  echo "Starting Ollama ..."
  nohup "$SCRIPT_DIR/start.sh" >"${TMPDIR:-/tmp}/ollama.log" 2>&1 &
  disown
  for _ in $(seq 1 30); do curl -sf "http://127.0.0.1:$OLLAMA_PORT/api/version" >/dev/null && break; sleep 1; done
fi

# Models: the Mac's entries in models.json that Ollama actually has. Each becomes a peer model
# (agents use its Ollama name) plus a selector carrying the readable name for llama-swap's UI.
MODELS_FILE="$SCRIPT_DIR/../models.json"
[ -f "$SCRIPT_DIR/../models.local.json" ] && MODELS_FILE="$SCRIPT_DIR/../models.local.json"
TAGS=$(curl -sf "http://127.0.0.1:$OLLAMA_PORT/api/tags") || { echo "Ollama is not answering on $OLLAMA_PORT (see ${TMPDIR:-/tmp}/ollama.log)." >&2; exit 1; }
ENTRIES=$(TAGS="$TAGS" python3 -c '
import json, os, sys
have = {m["name"].removesuffix(":latest") for m in json.loads(os.environ["TAGS"])["models"]}
for m in json.load(open(sys.argv[1]))["machines"].get("mac", []):
    if m["ollama"] in have:
        print("\t".join([m["ollama"], m["id"], json.dumps(m.get("name", m["id"])), json.dumps(m.get("desc", ""))]))
    else:
        print("skipping %s: not in Ollama (ollama pull %s, see ../README.md)" % (m["ollama"], m.get("source", "")), file=sys.stderr)
' "$MODELS_FILE")
[ -n "$ENTRIES" ] || { echo "None of the mac models in $MODELS_FILE is in Ollama." >&2; exit 1; }

mkdir -p "$CONFIG_DIR"
{
  echo "# Generated by llm/mac/llama-swap-setup.sh -- re-run it instead of editing."
  echo "logLevel: info"
  echo "peers:"
  echo "  ollama:"
  echo "    proxy: http://127.0.0.1:$OLLAMA_PORT"
  echo "    timeouts:"
  echo "      responseHeader: 600   # a cold model load plus a long prompt can exceed the 60 s default"
  echo "    filters:"
  echo "      setParams:"
  echo "        reasoning_effort: none   # OpenAI format (OpenCode, Pi)"
  echo "        thinking:                # Anthropic format (Claude Code); each format ignores the other's field"
  echo "          type: disabled"
  echo "    models:"
  while IFS=$'\t' read -r ollama _id _name _desc; do echo "      - $ollama"; done <<< "$ENTRIES"
  echo "selectors:"
  while IFS=$'\t' read -r ollama id name desc; do
    echo "  \"$id\":"
    echo "    strategy: pin"
    echo "    targets: [\"ollama/$ollama\"]"
    echo "    name: $name"
    echo "    description: $desc"
  done <<< "$ENTRIES"
} > "$CONFIG_FILE"
echo "Wrote $CONFIG_FILE:"
sed 's/^/  /' "$CONFIG_FILE"

if pgrep -x llama-swap >/dev/null 2>&1; then
  echo "llama-swap already running (restart to pick up a new config: ./stop.sh && ./llama-swap-setup.sh)"
else
  nohup "$LLAMA_SWAP_BIN" -config "$CONFIG_FILE" -listen "127.0.0.1:$SWAP_LISTEN" >"$LOG_FILE" 2>&1 &
  disown
  for _ in $(seq 1 20); do curl -sf "http://127.0.0.1:$SWAP_LISTEN/v1/models" >/dev/null && break; sleep 0.5; done
  curl -sf "http://127.0.0.1:$SWAP_LISTEN/v1/models" >/dev/null || { echo "llama-swap did not come up; see $LOG_FILE" >&2; exit 1; }
fi

pkill -f "local-proxy.py" 2>/dev/null || true
sleep 0.3
LOCAL_PROXY_UPSTREAM="http://127.0.0.1:$SWAP_LISTEN" LOCAL_PROXY_PORT="$AGENT_PORT" \
  nohup python3 "$SHARED_DIR/local-proxy.py" >"${TMPDIR:-/tmp}/local-proxy.log" 2>&1 &
disown
for _ in $(seq 1 20); do curl -s -o /dev/null "http://127.0.0.1:$AGENT_PORT/v1/models" && break; sleep 0.3; done

echo
echo "Agents:  http://127.0.0.1:$AGENT_PORT/v1  (./setup-agent.sh points OpenCode and Pi here)"
echo "Web UI:  http://127.0.0.1:$SWAP_LISTEN/ui"
