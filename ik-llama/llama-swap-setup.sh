#!/usr/bin/env bash
# Generates a llama-swap config.yaml from start.sh's MODES and (re)starts llama-swap
# plus local-proxy.py pointed at it, so agents can switch models by name instead of
# you running start.sh by hand. Usage: ./llama-swap-setup.sh <i9>
#
# Stack: harness -> local-proxy.py (9081, keep-alive) -> llama-swap (9082, model
# routing/lifecycle) -> llama-server (one at a time, port picked by llama-swap).
#
# This coexists with plain `start.sh i9 <mode>` (port 9080, manual, no swapping) --
# just don't run both against the same GGUF file's mlock'd RAM at once on a 62 GiB box.
set -euo pipefail

MACHINE="${1:-}"
[ "$MACHINE" = i9 ] || { echo "Usage: $0 i9  (llama-swap config is only generated for i9 so far)" >&2; exit 1; }

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MODELS_DIR="${MODELS_DIR:-$HOME/.local/share/llama.cpp/models}"
START_SCRIPT="$SCRIPT_DIR/start.sh"
SWAP_LISTEN="${IK_LLAMA_SWAP_PORT:-9082}"
AGENT_PORT="${IK_LLAMA_AGENT_PORT:-9081}"
CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/llama-swap"
CONFIG_FILE="$CONFIG_DIR/config.yaml"
HEALTH_TIMEOUT="${IK_LLAMA_SWAP_HEALTH_TIMEOUT:-600}"

LLAMA_SWAP_BIN="${LLAMA_SWAP_BIN:-$(command -v llama-swap || echo /home/linuxbrew/.linuxbrew/bin/llama-swap)}"
[ -x "$LLAMA_SWAP_BIN" ] || { echo "llama-swap not found. Install: brew tap mostlygeek/llama-swap && brew install mostlygeek/llama-swap/llama-swap" >&2; exit 1; }

# ── build config.yaml from start.sh's MODES (same regex setup-agents.sh uses) ──
_py=$(mktemp)
trap 'rm -f "$_py"' EXIT
cat > "$_py" << 'PYEOF'
import os, re, sys

models_dir = os.environ['MODELS_DIR']
start_script = os.environ['START_SCRIPT']
machine = os.environ['MACHINE']
start_script_abs = os.path.abspath(start_script)
health_timeout = int(os.environ['HEALTH_TIMEOUT'])

with open(start_script) as f:
    content = f.read()

in_config = False
in_block = False
modes_pattern = re.compile(r'"([^"|]+)\|([^"|]+\.gguf)\|(\d+)\|(\d+)')

entries = []
for line in content.split('\n'):
    if '# ── machine config' in line:
        in_config = True
    if not in_config:
        continue
    if re.match(r'^\s*' + re.escape(machine) + r'\)\s*$', line):
        in_block = True
        continue
    if in_block and re.search(r';;\s*$', line):
        break
    if not in_block:
        continue
    m = modes_pattern.search(line)
    if m:
        _desc, filename, _ctx, _cram = m.groups()
        model_id = filename[:-len('.gguf')]
        if os.path.isfile(os.path.join(models_dir, filename)):
            entries.append(model_id)

if not entries:
    print(f"No models found in {models_dir} for machine {machine}.", file=sys.stderr)
    sys.exit(1)

print("# Generated by llama-swap-setup.sh -- do not edit by hand, re-run the script instead.")
print("healthCheckTimeout: %d" % health_timeout)
print("models:")
for model_id in entries:
    print(f"  {model_id!r}:")
    # print_cmd reuses start.sh's own flag-building logic (SAMPLE/YARN/MMPROJ/SPEC
    # conditionals included) instead of duplicating it here; eval runs the real exec.
    print(f"    cmd: bash -c 'eval \"$(IK_LLAMA_PRINT_CMD=1 IK_LLAMA_PORT=${{PORT}} {start_script_abs!r} {machine} {model_id!r})\"'")
    print("    proxy: \"http://127.0.0.1:${PORT}\"")
    print("    ttl: 0")
PYEOF

mkdir -p "$CONFIG_DIR"
MODELS_DIR="$MODELS_DIR" START_SCRIPT="$START_SCRIPT" MACHINE="$MACHINE" HEALTH_TIMEOUT="$HEALTH_TIMEOUT" \
  python3 "$_py" > "$CONFIG_FILE.new"
mv "$CONFIG_FILE.new" "$CONFIG_FILE"
echo "Wrote $CONFIG_FILE:"
sed -n '/^models:/,$p' "$CONFIG_FILE" | grep -E '^\s{2}\S' | sed "s/^/  - /;s/://;s/'//g"

"$LLAMA_SWAP_BIN" -config "$CONFIG_FILE" -validate

if pgrep -f "llama-swap -config $CONFIG_FILE" >/dev/null 2>&1; then
  echo "llama-swap is already running with this config; restart it by hand to pick up changes (pkill -f llama-swap)."
else
  echo "Starting llama-swap on 127.0.0.1:$SWAP_LISTEN ..."
  nohup "$LLAMA_SWAP_BIN" -config "$CONFIG_FILE" -listen "127.0.0.1:$SWAP_LISTEN" >/tmp/llama-swap.log 2>&1 &
  disown
fi

echo "Pointing local-proxy.py (agent-facing port $AGENT_PORT) at llama-swap ..."
pkill -f "local-proxy.py" 2>/dev/null || true
sleep 0.3
LOCAL_PROXY_UPSTREAM="http://127.0.0.1:$SWAP_LISTEN" LOCAL_PROXY_PORT="$AGENT_PORT" \
  nohup python3 "$SCRIPT_DIR/local-proxy.py" >/tmp/local-proxy.log 2>&1 &
disown

echo
echo "Agents pointed at http://localhost:$AGENT_PORT/v1 can now request any of the models above by name;"
echo "llama-swap starts/stops the matching llama-server automatically. Re-run setup-agents.sh $MACHINE to list"
echo "them in OpenCode/Pi/cagent (same ids as before, no config change needed there)."
